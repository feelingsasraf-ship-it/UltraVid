export function findSampleMatch(urlStr: string): VideoMetadata | null {
  const normalized = urlStr.trim().toLowerCase();
  for (const sample of VERIFIED_SAMPLES) {
    if (sample.urlPatterns.some((p) => normalized.includes(p.toLowerCase()) || p.toLowerCase().includes(normalized))) {
      return JSON.parse(JSON.stringify(sample.metadata));
    }
  }
  return null;
}
